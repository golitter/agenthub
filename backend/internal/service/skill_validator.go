// ValidateZip 解压到临时目录并校验
func ValidateZip(zipData []byte) (*ValidationResult, string, error) {
	return ValidateZipReaderAt(bytes.NewReader(zipData), int64(len(zipData)))
}

// ValidateZipReaderAt validates an on-disk/random-access ZIP without first
// materializing the complete upload in memory.  The caller owns the reader and
// must provide its exact size.
func ValidateZipReaderAt(source io.ReaderAt, size int64) (*ValidationResult, string, error) {
	return ValidateZipReaderAtContext(context.Background(), source, size, "")
}

func ValidateZipReaderAtInDir(source io.ReaderAt, size int64, tempRoot string) (*ValidationResult, string, error) {
	return ValidateZipReaderAtContext(context.Background(), source, size, tempRoot)
}

func ValidateZipReaderAtContext(ctx context.Context, source io.ReaderAt, size int64, tempRoot string) (*ValidationResult, string, error) {
	return ValidateZipReaderAtContextWithLimits(ctx, source, size, tempRoot, DefaultZipLimits())
}

func ValidateZipReaderAtContextWithLimits(ctx context.Context, source io.ReaderAt, size int64, tempRoot string, limits ZipLimits) (*ValidationResult, string, error) {
	limits = limits.withDefaults()
	reader, err := zip.NewReader(source, size)
	if err != nil {
		return &ValidationResult{Valid: false, Errors: []string{"invalid zip file"}}, "", err
	}

	// 创建临时目录
	tmpDir, err := os.MkdirTemp(tempRoot, "skill-upload-*")
	if err != nil {
		return nil, "", fmt.Errorf("create temp dir: %w", err)
	}

	var (
		totalSize          int64
		fileCount          int
		errors             []string
		hasSkillMD         bool
		fmName             string
		fmDesc             string
		seenNames          = make(map[string]struct{}, len(reader.File))
		fileNames          []string
		containsExecutable bool
		containsBinary     bool
	)

	for _, f := range reader.File {
		if err := ctx.Err(); err != nil {
			_ = os.RemoveAll(tmpDir)
			return nil, tmpDir, err
		}
		cleanName, err := normalizeZipEntryName(f.Name)
		if err != nil {
			errors = append(errors, err.Error())
			continue
		}
		if f.NonUTF8 || !utf8.ValidString(f.Name) {
			errors = append(errors, "zip entry name must be UTF-8")
			continue
		}
		// Treat an explicit directory suffix as the same logical path as its
		// file spelling.  Otherwise an archive containing both ``foo`` and
		// ``foo/`` could evade duplicate detection and rely on filesystem
		// extraction order to decide which entry wins.
		collisionName := strings.ToLower(strings.TrimSuffix(cleanName, "/"))
		if _, exists := seenNames[collisionName]; exists {
			errors = append(errors, fmt.Sprintf("duplicate zip entry: %s", cleanName))
			continue
		}
		seenNames[collisionName] = struct{}{}

		// 链接、设备、管道和 socket 都不属于 Skill 普通文件。
		if f.Mode()&(os.ModeSymlink|os.ModeDevice|os.ModeNamedPipe|os.ModeSocket) != 0 {
			errors = append(errors, "special file types are not allowed")
			continue
		}

		destPath := filepath.Join(tmpDir, filepath.FromSlash(cleanName))
		if !isPathInside(tmpDir, destPath) {
			errors = append(errors, "path traversal detected")
			continue
		}

		if f.FileInfo().IsDir() {
			if err := os.MkdirAll(destPath, 0o755); err != nil {
				errors = append(errors, fmt.Sprintf("cannot create directory %s: %v", cleanName, err))
			}
			continue
		}
		if f.UncompressedSize64 > uint64(limits.FileSize) {
			errors = append(errors, fmt.Sprintf("file exceeds %dMB limit", limits.FileSize/1024/1024))
			continue
		}
		if compressionRatioExceeded(f.UncompressedSize64, f.CompressedSize64, limits.CompressionRatio) {
			errors = append(errors, fmt.Sprintf("compression ratio exceeds %d:1", limits.CompressionRatio))
			continue
		}
		if f.UncompressedSize64 > uint64(limits.UnpackedSize-totalSize) {
			errors = append(errors, fmt.Sprintf("zip bomb: total size exceeds %dMB", limits.UnpackedSize/1024/1024))
			_ = os.RemoveAll(tmpDir)
			return &ValidationResult{Valid: false, Errors: errors}, tmpDir, nil
		}

		// 确保父目录存在
		if err := os.MkdirAll(filepath.Dir(destPath), 0o755); err != nil {
			errors = append(errors, fmt.Sprintf("cannot create directory for %s: %v", cleanName, err))
			continue
		}

		rc, err := f.Open()
		if err != nil {
			errors = append(errors, fmt.Sprintf("cannot open %s: %v", cleanName, err))
			continue
		}

		remaining := limits.UnpackedSize - totalSize
		perFileRemaining := limits.FileSize
		if remaining < perFileRemaining {
			perFileRemaining = remaining
		}
		destMode := os.FileMode(0o644)
		if f.Mode().Perm()&0o111 != 0 {
			destMode = 0o755
		}
		destFile, err := os.OpenFile(destPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, destMode)
		if err != nil {
			rc.Close()
			errors = append(errors, fmt.Sprintf("cannot create %s: %v", cleanName, err))
			continue
		}
		if err := destFile.Chmod(destMode); err != nil {
			_ = destFile.Close()
			rc.Close()
			errors = append(errors, fmt.Sprintf("cannot secure %s: %v", cleanName, err))
			continue
		}
		n, err := io.Copy(destFile, io.LimitReader(contextReader{ctx: ctx, reader: rc}, perFileRemaining+1))
		closeErr := destFile.Close()
		rc.Close()
		if err != nil {
			errors = append(errors, fmt.Sprintf("cannot read %s: %v", cleanName, err))
			continue
		}
		if closeErr != nil {
			errors = append(errors, fmt.Sprintf("cannot write %s: %v", cleanName, closeErr))
			continue
		}
		if n > perFileRemaining {
			errors = append(errors, fmt.Sprintf("file exceeds %dMB limit", limits.FileSize/1024/1024))
			_ = os.RemoveAll(tmpDir)
			return &ValidationResult{Valid: false, Errors: errors}, tmpDir, nil
		}

		totalSize += n
		fileCount++
		fileNames = append(fileNames, cleanName)
		if f.Mode().Perm()&0o111 != 0 {
			containsExecutable = true
		}
		binary, binaryErr := fileLooksBinary(destPath)
		if binaryErr != nil {
			errors = append(errors, fmt.Sprintf("cannot inspect binary content for %s: %v", cleanName, binaryErr))
			continue
		}
		if binary {
			containsBinary = true
		}

		// Zip bomb 检查
		if fileCount > limits.FileCount {
			errors = append(errors, fmt.Sprintf("too many files: exceeds %d", limits.FileCount))
			os.RemoveAll(tmpDir)
			return &ValidationResult{Valid: false, Errors: errors}, tmpDir, nil
		}

		// 检查 SKILL.md（根目录或一级子目录，如 skill-name/SKILL.md）
		if filepath.Base(cleanName) == SkillMDFile && !strings.Contains(filepath.Dir(cleanName), "/") {
			hasSkillMD = true
			data, readErr := os.ReadFile(destPath)
			if readErr != nil {
				errors = append(errors, fmt.Sprintf("cannot read %s: %v", cleanName, readErr))
				continue
			}
			name, desc, parseErr := parseFrontmatter(data)
			if parseErr != nil {
				errors = append(errors, parseErr.Error())
			} else {
				fmName = name
				fmDesc = desc
			}
		}
	}

	if !hasSkillMD {
		errors = append(errors, "missing SKILL.md")
	}
	if entries, readErr := os.ReadDir(tmpDir); readErr == nil {
		rootDirs := make([]string, 0, 1)
		rootFiles := 0
		_, rootSkillErr := os.Stat(filepath.Join(tmpDir, SkillMDFile))
		hasRootSkillMD := rootSkillErr == nil
		for _, entry := range entries {
			if entry.IsDir() {
				rootDirs = append(rootDirs, entry.Name())
			} else {
				rootFiles++
			}
		}
		// A root-level SKILL.md makes the package root the Skill root, so content
		// files and directories may sit beside it.  The alternate layout is
		// exactly one named top-level Skill directory with no sibling files.
		rootLayout := hasRootSkillMD
		nestedLayout := !hasRootSkillMD && len(rootDirs) == 1 && rootFiles == 0 && fmName != "" && rootDirs[0] == fmName
		if !rootLayout && !nestedLayout {
			errors = append(errors, "zip must contain a root SKILL.md or one top-level Skill directory matching SKILL.md.name")
		}
	} else {
		errors = append(errors, fmt.Sprintf("cannot inspect Skill root: %v", readErr))
	}

	if len(errors) > 0 {
		return &ValidationResult{Valid: false, Errors: errors}, tmpDir, nil
	}

	sort.Strings(fileNames)
	return &ValidationResult{
		Valid:              true,
		Name:               fmName,
		Description:        fmDesc,
		FileCount:          fileCount,
		Files:              fileNames,
		ContainsExecutable: containsExecutable,
		ContainsBinary:     containsBinary,
		TotalSize:          totalSize,
		TmpDir:             tmpDir,
	}, tmpDir, nil
}

// ValidateCanonicalSkillPackageContext rechecks a generated, deterministic
// ZIP with the same limits used for the source archive.  Repacking can change
// the compression ratio (for example, a stored input may become highly
// compressed), so validating only the original upload is not sufficient for
// the AgentEnd boundary.
func ValidateCanonicalSkillPackageContext(ctx context.Context, source io.ReaderAt, size int64, tempRoot, expectedName string, limits ZipLimits) error {
	result, tmpDir, err := ValidateZipReaderAtContextWithLimits(ctx, source, size, tempRoot, limits)
	if tmpDir != "" {
		defer os.RemoveAll(tmpDir)
	}
	if err != nil {
		return fmt.Errorf("canonical Skill package validation failed: %w", err)
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	if result == nil || !result.Valid {
		if result != nil && len(result.Errors) > 0 {
			return fmt.Errorf("canonical Skill package validation failed: %s", strings.Join(result.Errors, "; "))
		}
		return fmt.Errorf("canonical Skill package validation failed")
	}
	if expectedName != "" && result.Name != expectedName {
		return fmt.Errorf("canonical Skill package name %q does not match %q", result.Name, expectedName)
	}
	return nil
}

func compressionRatioExceeded(uncompressed, compressed uint64, ratio int64) bool {
	if uncompressed == 0 {
		return false
	}
	if compressed == 0 || ratio <= 0 {
		return true
	}
	// Compare ceil(uncompressed/ratio) with compressed to avoid multiplying
	// attacker-controlled ZIP64 fields and overflowing uint64.
	divisor := uint64(ratio)
	minimumCompressed := uncompressed / divisor
	if uncompressed%divisor != 0 {
		minimumCompressed++
	}
	return minimumCompressed > compressed
}

type contextReader struct {
	ctx    context.Context
	reader io.Reader
}

func fileLooksBinary(path string) (bool, error) {
	file, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer file.Close()
	buf := make([]byte, 8192)
	n, err := file.Read(buf)
	if err != nil && err != io.EOF {
		return false, err
	}
	return bytes.IndexByte(buf[:n], 0) >= 0, nil
}

func (r contextReader) Read(p []byte) (int, error) {
	select {
	case <-r.ctx.Done():
		return 0, r.ctx.Err()
	default:
		return r.reader.Read(p)
	}
}

func normalizeZipEntryName(name string) (string, error) {
	if name == "" {
		return "", fmt.Errorf("empty zip entry name")
	}
	if name != strings.TrimSpace(name) {
		return "", fmt.Errorf("non-canonical zip entry path")
	}
	for _, r := range name {
		if r < 0x20 || r == 0x7f {
			return "", fmt.Errorf("control characters are not allowed in zip entry names")
		}
	}
	if strings.Contains(name, "\\") {
		return "", fmt.Errorf("backslash path separator not allowed")
	}
	if filepath.IsAbs(name) || strings.HasPrefix(name, "/") {
		return "", fmt.Errorf("absolute path not allowed")
	}
	// Reject non-canonical spellings before filepath.Clean can hide a
	// traversal segment.  A path such as foo/../SKILL.md stays inside the
	// extraction root, but accepting it would make Backend and AgentEnd
	// disagree about duplicate/canonical entries and could bypass manifest
	// comparisons.  Directory entries may have one trailing slash only.
	trailingSlash := strings.HasSuffix(name, "/")
	trimmedName := strings.TrimSuffix(name, "/")
	parts := strings.Split(trimmedName, "/")
	if trimmedName == "" || len(parts) == 0 {
		return "", fmt.Errorf("empty zip entry name")
	}
	for _, segment := range parts {
		if segment == "" || segment == "." || segment == ".." {
			return "", fmt.Errorf("non-canonical zip entry path")
		}
	}
	canonical := strings.Join(parts, "/")
	if trailingSlash {
		// Keep the normalized entry name free of a trailing slash; the archive
		// metadata still determines whether it is a directory.
		name = canonical + "/"
	} else {
		name = canonical
	}
	cleanName := filepath.ToSlash(filepath.Clean(name))
	if cleanName == "." || cleanName == "" {
		return "", fmt.Errorf("empty zip entry name")
	}
	if strings.Contains(strings.Split(cleanName, "/")[0], ":") {
		return "", fmt.Errorf("drive-qualified zip entry path not allowed")
	}
	return cleanName, nil
}

func isPathInside(baseDir, targetPath string) bool {
	rel, err := filepath.Rel(baseDir, targetPath)
	if err != nil {
		return false
	}
	return rel != "." && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

// parseFrontmatter 解析 SKILL.md 的 YAML frontmatter
func parseFrontmatter(data []byte) (name, description string, err error) {
	if !utf8.Valid(data) {
		return "", "", fmt.Errorf("SKILL.md must be UTF-8")
	}
	content := strings.ReplaceAll(string(data), "\r\n", "\n")
	if !strings.HasPrefix(content, "---\n") {
		return "", "", fmt.Errorf("missing frontmatter")
	}
	lines := strings.Split(content[4:], "\n")
	closing := -1
	for index, line := range lines {
		if strings.TrimSpace(line) == "---" {
			closing = index
			break
		}
	}
	if closing < 0 {
		return "", "", fmt.Errorf("missing frontmatter")
	}
	fmContent := strings.TrimSpace(strings.Join(lines[:closing], "\n"))
	var fm frontmatterData
	if err := yaml.Unmarshal([]byte(fmContent), &fm); err != nil {
		return "", "", fmt.Errorf("invalid frontmatter: %v", err)
	}

	name, nameErr := NormalizeSkillName(fm.Name)
	if nameErr != nil {
		return "", "", nameErr
	}
	if len([]rune(fm.Description)) > 4096 {
		return "", "", fmt.Errorf("description field is too long")
	}

	return name, fm.Description, nil
}

// PackValidatedSkillDir 将已校验的技能目录重新打包为 zip 字节流。
func PackValidatedSkillDir(name string, tmpDir string) ([]byte, error) {
	return PackValidatedSkillDirWithLimit(name, tmpDir, MaxPackageSize)
}

// PackValidatedSkillDirWithLimit is the compatibility-path counterpart of
// the streaming packer. It keeps the legacy API bounded when an operator uses
// a stricter configured package limit.
func PackValidatedSkillDirWithLimit(name string, tmpDir string, maxPackageSize int64) ([]byte, error) {
	srcDir, err := validatedSkillSourceDir(name, tmpDir)
	if err != nil {
		return nil, err
	}

	// 将已校验的文件重新打包为 zip
	zipData, err := zipDirWithLimit(srcDir, maxPackageSize)
	if err != nil {
		return nil, fmt.Errorf("pack skill files: %w", err)
	}

	return zipData, nil
}

// PackValidatedSkillDirInRoot is the trusted counterpart used immediately
// after ValidateZipReaderAtContext.  The validator may be configured with a
// private volume outside os.TempDir; the legacy public helper deliberately
// keeps its stricter system-temp check because it accepts client-supplied
// paths during the compatibility confirm flow.
func PackValidatedSkillDirInRoot(name, tmpDir, tempRoot string) ([]byte, error) {
	return PackValidatedSkillDirInRootContext(context.Background(), name, tmpDir, tempRoot)
}

// PackValidatedSkillDirInRootContext is the cancellation-aware variant used
// by uploads and migration. Packing reads every extracted file, so checking
// only the unzip phase would allow slow filesystem I/O to outlive the request
// validation deadline.
func PackValidatedSkillDirInRootContext(ctx context.Context, name, tmpDir, tempRoot string) ([]byte, error) {
	return PackValidatedSkillDirInRootContextWithLimit(ctx, name, tmpDir, tempRoot, MaxPackageSize)
}

// PackValidatedSkillDirInRootContextWithLimit aborts as soon as the
// deterministic archive exceeds maxPackageSize instead of constructing an
// oversized ZIP and checking it only after the write has completed.
func PackValidatedSkillDirInRootContextWithLimit(ctx context.Context, name, tmpDir, tempRoot string, maxPackageSize int64) ([]byte, error) {
	srcDir, err := validatedSkillSourceDirInRoot(name, tmpDir, tempRoot)
	if err != nil {
		return nil, err
	}
	if maxPackageSize <= 0 {
		maxPackageSize = MaxPackageSize
	}
	var buf bytes.Buffer
	err = zipDirToWriterContext(ctx, srcDir, &limitedWriter{dst: &buf, limit: maxPackageSize})
	if err != nil {
		return nil, fmt.Errorf("pack skill files: %w", err)
	}
	return buf.Bytes(), nil
}

