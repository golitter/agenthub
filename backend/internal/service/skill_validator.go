func inspectValidatedSkillSourceDir(name, srcDir string, limits ZipLimits) (*ValidationResult, error) {
	limits = limits.withDefaults()

	result := &ValidationResult{Valid: true}
	err := filepath.Walk(srcDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return fmt.Errorf("walk error at %s: %w", path, err)
		}
		if info.Mode()&(os.ModeSymlink|os.ModeDevice|os.ModeNamedPipe|os.ModeSocket) != 0 {
			return fmt.Errorf("symbolic links and special file types are not allowed")
		}
		if info.IsDir() {
			return nil
		}

		result.FileCount++
		if result.FileCount > limits.FileCount {
			return fmt.Errorf("too many files: exceeds %d", limits.FileCount)
		}
		result.TotalSize += info.Size()
		if info.Size() > limits.FileSize {
			return fmt.Errorf("file exceeds %dMB limit", limits.FileSize/1024/1024)
		}
		if result.TotalSize > limits.UnpackedSize {
			return fmt.Errorf("total size exceeds %dMB", limits.UnpackedSize/1024/1024)
		}

		rel, err := filepath.Rel(srcDir, path)
		if err != nil {
			return fmt.Errorf("relative path error: %w", err)
		}
		rel = filepath.ToSlash(rel)
		result.Files = append(result.Files, rel)
		if info.Mode().Perm()&0o111 != 0 {
			result.ContainsExecutable = true
		}
		binary, binaryErr := fileLooksBinary(path)
		if binaryErr != nil {
			return fmt.Errorf("inspect binary content at %s: %w", rel, binaryErr)
		}
		if binary {
			result.ContainsBinary = true
		}
		if filepath.Base(rel) == SkillMDFile && !strings.Contains(pathpkgDir(rel), "/") {
			data, err := os.ReadFile(path)
			if err != nil {
				return fmt.Errorf("read %s: %w", SkillMDFile, err)
			}
			skillName, desc, err := parseFrontmatter(data)
			if err != nil {
				return err
			}
			result.Name = skillName
			result.Description = desc
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	if result.Name == "" {
		return nil, fmt.Errorf("missing %s", SkillMDFile)
	}
	if result.Name != name {
		return nil, fmt.Errorf("skill name mismatch: confirm name (%s) does not match SKILL.md name (%s)", name, result.Name)
	}
	sort.Strings(result.Files)
	return result, nil
}

func validatedSkillSourceDir(name string, tmpDir string) (string, error) {
	safeTmpDir, err := ensureSkillUploadTmpDir(tmpDir)
	if err != nil {
		return "", err
	}
	return skillSourceDir(name, safeTmpDir), nil
}

func validatedSkillSourceDirInRoot(name, tmpDir, tempRoot string) (string, error) {
	safeTmpDir, err := ensureSkillUploadTmpDirInRoot(tmpDir, tempRoot)
	if err != nil {
		return "", err
	}
	return skillSourceDir(name, safeTmpDir), nil
}

func skillSourceDir(name, safeTmpDir string) string {
	// A root-level SKILL.md defines the package root, even when a sibling
	// directory happens to share the Skill name.  Prefer it before probing the
	// alternate single-top-level-directory layout; otherwise canonical packing
	// could silently omit root-level files from an otherwise valid package.
	if info, err := os.Stat(filepath.Join(safeTmpDir, SkillMDFile)); err == nil && info.Mode().IsRegular() {
		return safeTmpDir
	}
	srcDir := filepath.Join(safeTmpDir, name)
	if info, err := os.Stat(srcDir); err != nil || !info.IsDir() {
		srcDir = safeTmpDir
	}
	return srcDir
}

func ensureSkillUploadTmpDir(tmpDir string) (string, error) {
	return ensureSkillUploadTmpDirInRoot(tmpDir, os.TempDir())
}

func ensureSkillUploadTmpDirInRoot(tmpDir, tempRoot string) (string, error) {
	if tmpDir == "" {
		return "", fmt.Errorf("tmp_dir is required")
	}

	absTmpDir, err := filepath.Abs(tmpDir)
	if err != nil {
		return "", fmt.Errorf("invalid tmp_dir: %w", err)
	}
	if tempRoot == "" {
		tempRoot = os.TempDir()
	}
	absSystemTmp, err := filepath.Abs(tempRoot)
	if err != nil {
		return "", fmt.Errorf("invalid system tmp dir: %w", err)
	}

	if filepath.Dir(absTmpDir) != absSystemTmp || !strings.HasPrefix(filepath.Base(absTmpDir), "skill-upload-") {
		return "", fmt.Errorf("invalid skill upload tmp_dir")
	}
	rootInfo, err := os.Lstat(absSystemTmp)
	if err != nil || rootInfo.Mode()&os.ModeSymlink != 0 || !rootInfo.IsDir() {
		return "", fmt.Errorf("invalid skill upload temp root")
	}

	info, err := os.Lstat(absTmpDir)
	if err != nil {
		return "", fmt.Errorf("invalid skill upload tmp_dir: %w", err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() || !ownedByCurrentUser(info) {
		return "", fmt.Errorf("invalid skill upload tmp_dir")
	}
	if info.Mode().Perm()&0o077 != 0 {
		return "", fmt.Errorf("skill upload tmp_dir must not be group/world accessible")
	}
	return absTmpDir, nil
}

// CleanupSkillUploadTempDir removes only stale directories/files created by
// the Skill upload path.  It never follows links and never traverses unrelated
// entries in the temp volume.
func CleanupSkillUploadTempDir(root string, olderThan time.Duration) (int, error) {
	if strings.TrimSpace(root) == "" || olderThan <= 0 {
		return 0, nil
	}
	rootInfo, err := os.Lstat(root)
	if err != nil {
		if os.IsNotExist(err) {
			return 0, nil
		}
		return 0, err
	}
	if rootInfo.Mode()&os.ModeSymlink != 0 || !rootInfo.IsDir() {
		return 0, fmt.Errorf("skill temp root is not a directory")
	}
	entries, err := os.ReadDir(root)
	if err != nil {
		return 0, err
	}
	cutoff := time.Now().Add(-olderThan)
	removed := 0
	for _, entry := range entries {
		if !strings.HasPrefix(entry.Name(), "skill-upload-") && !strings.HasPrefix(entry.Name(), ".canonical-") {
			continue
		}
		path := filepath.Join(root, entry.Name())
		info, err := os.Lstat(path)
		if err != nil || info.Mode()&os.ModeSymlink != 0 || info.ModTime().After(cutoff) || !ownedByCurrentUser(info) {
			continue
		}
		if err := os.RemoveAll(path); err != nil {
			return removed, err
		}
		removed++
	}
	return removed, nil
}

func ownedByCurrentUser(info os.FileInfo) bool {
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return true
	}
	return stat.Uid == uint32(os.Getuid())
}

func pathpkgDir(p string) string {
	dir := filepath.ToSlash(filepath.Dir(p))
	if dir == "." {
		return ""
	}
	return dir
}

// zipDir 将目录打包为可复现的 zip 字节流。
// 目录遍历顺序、时间戳和权限都显式归一化，避免同一份 Skill 因临时目录
// 或宿主机元数据不同而生成不同的对象哈希。当前接口仍返回 []byte；后续
// 按规划切换到临时文件流式打包时，应保持这里的规范化规则不变。
func zipDir(src string) ([]byte, error) {
	return zipDirWithLimit(src, MaxPackageSize)
}

func zipDirWithLimit(src string, maxPackageSize int64) ([]byte, error) {
	var buf bytes.Buffer
	if maxPackageSize <= 0 {
		maxPackageSize = MaxPackageSize
	}
	if err := zipDirToWriterContext(context.Background(), src, &limitedWriter{dst: &buf, limit: maxPackageSize}); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

type limitedWriter struct {
	dst   io.Writer
	limit int64
	n     int64
}

func (w *limitedWriter) Write(p []byte) (int, error) {
	if w.limit > 0 && w.n+int64(len(p)) > w.limit {
		remaining := w.limit - w.n
		if remaining > 0 {
			written, err := w.dst.Write(p[:remaining])
			w.n += int64(written)
			if err != nil {
				return written, err
			}
			return written, fmt.Errorf("canonical package exceeds %d bytes", w.limit)
		}
		return 0, fmt.Errorf("canonical package exceeds %d bytes", w.limit)
	}
	written, err := w.dst.Write(p)
	w.n += int64(written)
	return written, err
}

func zipDirToWriter(src string, dst io.Writer) error {
	return zipDirToWriterContext(context.Background(), src, dst)
}

func zipDirToWriterContext(ctx context.Context, src string, dst io.Writer) error {
	w := zip.NewWriter(dst)
	type fileEntry struct {
		path string
		rel  string
		mode os.FileMode
		size int64
	}
	entries := make([]fileEntry, 0)
	err := filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return fmt.Errorf("walk error at %s: %w", path, err)
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("symbolic links not allowed")
		}
		if info.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return fmt.Errorf("relative path error: %w", err)
		}
		rel = filepath.ToSlash(rel) // 统一正斜杠，跨平台一致
		entries = append(entries, fileEntry{path: path, rel: rel, mode: info.Mode(), size: info.Size()})
		return nil
	})
	if err != nil {
		return err
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].rel < entries[j].rel })
	if len(entries) > MaxFileCount {
		return fmt.Errorf("too many files: exceeds %d", MaxFileCount)
	}
	var totalSize int64
	for _, entry := range entries {
		if err := ctx.Err(); err != nil {
			return err
		}
		totalSize += entry.size
		if entry.size > MaxFileSize {
			return fmt.Errorf("file exceeds %dMB limit", MaxFileSize/1024/1024)
		}
		if totalSize > MaxUnpackedSize {
			return fmt.Errorf("total size exceeds %dMB", MaxUnpackedSize/1024/1024)
		}
		header := &zip.FileHeader{Name: entry.rel, Method: zip.Deflate}
		// ZIP DOS timestamps cannot represent Unix epoch; archive/zip clamps
		// this value consistently, which is still deterministic across hosts.
		header.SetModTime(time.Unix(0, 0).UTC())
		if entry.mode.Perm()&0o111 != 0 {
			header.SetMode(0o755)
		} else {
			header.SetMode(0o644)
		}
		f, err := w.CreateHeader(header)
		if err != nil {
			return err
		}
		in, err := os.Open(entry.path)
		if err != nil {
			return err
		}
		_, err = io.Copy(f, contextReader{ctx: ctx, reader: in})
		closeErr := in.Close()
		if err != nil {
			return err
		}
		if closeErr != nil {
			return closeErr
		}
	}
	if err := w.Close(); err != nil {
		return err
	}
	return nil
}
