const (
	MaxUploadSize       int64 = 10 * 1024 * 1024
	MaxPackageSize      int64 = 12 * 1024 * 1024
	MaxFileSize         int64 = 10 * 1024 * 1024
	MaxUnpackedSize     int64 = 50 * 1024 * 1024
	MaxCompressionRatio       = 100
	MaxFileCount        int   = 200
	// MaxUnzipSize is kept as a compatibility alias for callers that used the
	// old single-limit API; new code must distinguish upload/package/unpacked
	// limits above.
	MaxUnzipSize          int64 = MaxPackageSize
	SkillMDFile                 = "SKILL.md"
	MinSkillTempFreeBytes int64 = 1 << 30
)

const MaxSkillNameLength = 128

var skillUploadIDPattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_-]{7,63}$`)

// ValidateSkillUploadID accepts the current UUID IDs and future opaque IDs
// such as ULIDs while rejecting values that could alter Redis keys or object
// paths.  IDs are generated by the Backend; this check is only a boundary
// guard for client-supplied confirmation requests.
func ValidateSkillUploadID(id string) error {
	if !skillUploadIDPattern.MatchString(id) {
		return ErrBadRequest("invalid upload_id")
	}
	return nil
}

// NormalizeSkillName is the shared object-key and API name policy.  Keeping it
// in the validator package makes upload, legacy migration, and object-key
// construction reject the same path/control-character edge cases.
func NormalizeSkillName(name string) (string, error) {
	name = strings.TrimSpace(name)
	if name == "" || name == "." || name == ".." {
		return "", ErrBadRequest("skill name is required")
	}
	if len([]rune(name)) > MaxSkillNameLength {
		return "", ErrBadRequest("skill name is too long")
	}
	if strings.ContainsAny(name, "/\\") {
		return "", ErrBadRequest("skill name is invalid")
	}
	for _, r := range name {
		if r < 0x20 || r == 0x7f {
			return "", ErrBadRequest("skill name is invalid")
		}
	}
	return name, nil
}

func CheckSkillTempFreeSpace(root string, minimum int64) error {
	if root == "" {
		root = os.TempDir()
	}
	if minimum <= 0 {
		minimum = MinSkillTempFreeBytes
	}
	var stat syscall.Statfs_t
	if err := syscall.Statfs(root, &stat); err != nil {
		return fmt.Errorf("stat Skill temp volume: %w", err)
	}
	free := int64(stat.Bavail) * int64(stat.Bsize)
	if free < minimum {
		return fmt.Errorf("Skill temp volume free space %d bytes is below reserved %d bytes", free, minimum)
	}
	return nil
}

// EnsureSkillTempRoot creates and validates the private staging root used by
// the upload path.  A symlink at any path component is rejected so an
// operator cannot accidentally redirect extraction into an unrelated tree.
func EnsureSkillTempRoot(root string) error {
	if strings.TrimSpace(root) == "" {
		return fmt.Errorf("Skill temp root is required")
	}
	abs, err := filepath.Abs(root)
	if err != nil {
		return fmt.Errorf("resolve Skill temp root: %w", err)
	}
	// MkdirAll follows a symlink in a parent component. Walk existing
	// components first so a rejected configuration cannot create staging data
	// in an unrelated target before validation notices the link.
	if err := ensurePrivateDirPath(abs); err != nil {
		return fmt.Errorf("create Skill temp root: %w", err)
	}
	info, err := os.Lstat(abs)
	if err != nil {
		return fmt.Errorf("inspect Skill temp root: %w", err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		return fmt.Errorf("Skill temp root must be a real directory")
	}
	resolved, err := filepath.EvalSymlinks(abs)
	if err != nil {
		return fmt.Errorf("resolve Skill temp root links: %w", err)
	}
	if filepath.Clean(resolved) != filepath.Clean(abs) {
		return fmt.Errorf("Skill temp root must not contain symlinks")
	}
	if err := os.Chmod(abs, 0o700); err != nil {
		return fmt.Errorf("secure Skill temp root: %w", err)
	}
	return nil
}

func ensurePrivateDirPath(abs string) error {
	volume := filepath.VolumeName(abs)
	remainder := strings.TrimPrefix(abs, volume)
	current := volume
	if strings.HasPrefix(remainder, string(filepath.Separator)) {
		current += string(filepath.Separator)
		remainder = strings.TrimPrefix(remainder, string(filepath.Separator))
	}
	if current == "" {
		current = "."
	}
	for _, component := range strings.Split(remainder, string(filepath.Separator)) {
		if component == "" || component == "." {
			continue
		}
		current = filepath.Join(current, component)
		info, err := os.Lstat(current)
		if errors.Is(err, os.ErrNotExist) {
			if err := os.Mkdir(current, 0o700); err != nil && !errors.Is(err, os.ErrExist) {
				return err
			}
			info, err = os.Lstat(current)
		}
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
			return fmt.Errorf("path component %q is not a real directory", current)
		}
	}
	return nil
}

// ZipLimits is the single source of truth for archive resource limits.  The
// exported constants preserve the historical defaults for callers that do not
// have a config object yet.
type ZipLimits struct {
	UploadSize       int64
	PackageSize      int64
	FileSize         int64
	UnpackedSize     int64
	CompressionRatio int64
	FileCount        int
}

func DefaultZipLimits() ZipLimits {
	return ZipLimits{
		UploadSize: MaxUploadSize, PackageSize: MaxPackageSize, FileSize: MaxFileSize,
		UnpackedSize: MaxUnpackedSize, CompressionRatio: MaxCompressionRatio, FileCount: MaxFileCount,
	}
}

func (l ZipLimits) withDefaults() ZipLimits {
	d := DefaultZipLimits()
	if l.UploadSize <= 0 {
		l.UploadSize = d.UploadSize
	}
	if l.PackageSize <= 0 {
		l.PackageSize = d.PackageSize
	}
	if l.FileSize <= 0 {
		l.FileSize = d.FileSize
	}
	if l.UnpackedSize <= 0 {
		l.UnpackedSize = d.UnpackedSize
	}
	if l.CompressionRatio <= 0 {
		l.CompressionRatio = d.CompressionRatio
	}
	if l.FileCount <= 0 {
		l.FileCount = d.FileCount
	}
	return l
}

func NormalizeZipLimits(l ZipLimits) ZipLimits { return l.withDefaults() }

